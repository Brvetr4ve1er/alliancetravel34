// tools/i18n-manifest.mjs
// Extracts the FR/EN/AR translation contract from RENDERED trip pages.
//
// Why rendered HTML and not data/trips/*.json: the site's public dictionary
// (site/assets/js/i18n.js, the "k.*" namespace) only carries the ~50 shared
// strings (nav, footer, hero chrome, etc). The 200+ trip-specific bindings
// (data-i18n / data-i18n-html on the rendered page) only ever coexist in the
// built HTML — that is the sole source of truth for "what needs a translation".
//
// No DOM library is used or added here (zero-dependency repo, strict CSP).
// Extraction is a hand-rolled regex scan with a depth-aware close-tag finder,
// which is sufficient because trip pages are machine-generated by
// tools/build.mjs and never nest a data-i18n(-html) element inside another
// element of the same tag name.

const BINDING_ATTR_RE = /<([a-zA-Z][a-zA-Z0-9]*)\b[^>]*?\bdata-i18n(-html)?="([^"]*)"[^>]*>/g;

/**
 * Find the index of the closing tag that matches the opening tag at `start`,
 * tracking nesting depth for tags of the same name so a nested element with
 * the same tag name doesn't terminate the scan early.
 * Returns -1 if no matching close tag is found (malformed markup).
 */
function findMatchingClose(html, tag, start) {
  const tagRe = new RegExp(`<(/?)${tag}(?=[\\s/>])[^>]*>`, "gi");
  tagRe.lastIndex = start;
  let depth = 1;
  let m;
  while ((m = tagRe.exec(html))) {
    const isClose = m[1] === "/";
    const selfClosing = /\/>$/.test(m[0]);
    if (isClose) {
      depth -= 1;
      if (depth === 0) return m.index;
    } else if (!selfClosing) {
      depth += 1;
    }
  }
  return -1;
}

/** Strip tags and collapse whitespace — what the runtime's plain-text
 * `data-i18n` compare (el.textContent) effectively sees. */
function normalizePlainText(raw) {
  return raw.replace(/<[^>]*>/g, "").replace(/\s+/g, " ").trim();
}

/**
 * extractBindings(html) -> [{ key, fr, isHtml }]
 * Scans rendered HTML for `data-i18n="KEY"` and `data-i18n-html="KEY"`
 * bindings, in document order (duplicates included — a key can appear on
 * more than one element, e.g. a price repeated in a sticky bar).
 */
export function extractBindings(html) {
  const bindings = [];
  BINDING_ATTR_RE.lastIndex = 0;
  let match;
  while ((match = BINDING_ATTR_RE.exec(html))) {
    const tag = match[1];
    const isHtml = match[2] === "-html";
    const key = match[3];
    const contentStart = match.index + match[0].length;
    const closeIndex = findMatchingClose(html, tag, contentStart);
    if (closeIndex === -1) continue; // malformed markup — skip rather than misparse
    const inner = html.slice(contentStart, closeIndex);
    const fr = isHtml ? inner.trim() : normalizePlainText(inner);
    bindings.push({ key, fr, isHtml });
    BINDING_ATTR_RE.lastIndex = closeIndex;
  }
  return bindings;
}

/**
 * frHash(text) -> string
 * FNV-1a (32-bit), base36, zero-padded to 8 chars. Deterministic, no crypto
 * import. Exported for reuse by the staleness gate and the admin UI, which
 * both need to compare a stored hash against a freshly-extracted `fr` string.
 */
export function frHash(text) {
  const str = String(text);
  let hash = 0x811c9dc5;
  for (let i = 0; i < str.length; i++) {
    hash ^= str.charCodeAt(i);
    hash = Math.imul(hash, 0x01000193);
  }
  return (hash >>> 0).toString(36).padStart(8, "0");
}

function stateFor(value, storedHash, currentFrHash) {
  if (value == null || value === "") return "missing";
  if (storedHash && storedHash === currentFrHash) return "ok";
  return "stale";
}

/**
 * buildManifest({ slug, html, trip, sharedKeys }) ->
 *   { slug, coverage: {en, ar}, keys: { [key]: {fr, frHash, en, ar, enHash, arHash, scope, enState, arState} } }
 *
 * - scope: "shared" for keys translated once globally (nav.*, heroFrom, …),
 *   "trip" for everything specific to this trip page.
 * - enState/arState: "missing" | "stale" | "ok" (see stateFor).
 * - coverage.{en,ar}: % of trip-scope keys PRESENT in that language (ok or stale).
 *   i18nHash is a new, currently-absent block on every trip's JSON, so on
 *   first run every existing translation reads as "stale" — expected, honest,
 *   and fixed by the stamping step that ships later in this milestone.
 */
export function buildManifest({ slug, html, trip, sharedKeys }) {
  const bindings = extractBindings(html);
  const en = (trip && trip.i18n && trip.i18n.en) || {};
  const ar = (trip && trip.i18n && trip.i18n.ar) || {};
  const enHashes = (trip && trip.i18nHash && trip.i18nHash.en) || {};
  const arHashes = (trip && trip.i18nHash && trip.i18nHash.ar) || {};

  const keys = {};
  for (const b of bindings) {
    if (keys[b.key]) continue; // first occurrence wins; duplicates share one FR source
    const scope = sharedKeys && sharedKeys.has(b.key) ? "shared" : "trip";
    const hash = frHash(b.fr);
    const enVal = en[b.key];
    const arVal = ar[b.key];
    const enHash = enHashes[b.key];
    const arHash = arHashes[b.key];
    keys[b.key] = {
      fr: b.fr,
      frHash: hash,
      en: enVal,
      ar: arVal,
      enHash,
      arHash,
      scope,
      enState: stateFor(enVal, enHash, hash),
      arState: stateFor(arVal, arHash, hash),
    };
  }

  // Coverage answers "how much of this page exists in that language", so a
  // stale translation still counts — it is present, merely out of date.
  // Freshness is reported separately, per key, via enState/arState.
  //
  // Counting only "ok" would read 0% on every trip until the one-time hash
  // stamping lands, which would tell the owner egypte is untranslated when it
  // is 92% translated — a worse lie than the staleness it was meant to expose.
  const tripKeys = Object.values(keys).filter((k) => k.scope === "trip");
  const pct = (state) =>
    tripKeys.length === 0
      ? 0
      : Math.round((tripKeys.filter((k) => k[state] !== "missing").length / tripKeys.length) * 100);

  return {
    slug,
    coverage: { en: pct("enState"), ar: pct("arState") },
    keys,
  };
}
